void solve() {
    ll L, v0, T, N; cin >> L >> v0 >> T >> N;
    for(int i = 0; i < N; i++) {
        ll ti, vi; cin >> ti >> vi;
        ll r = abs(v0 - vi);
        if(i) cout << " ";
        cout << 1+(T-ti)*r/L;
    }
}

//king of the sun o_O
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    int t; cin >> t;
    //int t = 1;
    while(t--) {
        solve();
        if(t)   cout << "\n";
    }
}

