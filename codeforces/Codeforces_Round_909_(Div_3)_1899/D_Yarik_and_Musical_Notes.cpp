#include<bits/stdc++.h>
 
using namespace std;
 
using ll = long long;
using ld = long double;
 
void solve() {
    int n; cin >> n;
    vector<int> a(n); for(int &i : a) cin >> i;
    map<int, int> mp;
    for(int x : a) mp[x]++;
    ll ans = ll(mp[1])*mp[2];
    for(auto &p : mp) {
        ans += ll(p.second)*(p.second-1)/2;
    }

    cout << ans;
}
 
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    int t; cin >> t;
    //int t = 1;
    while(t--) {
        solve();
        if(t)   cout << "\n";
    }
}