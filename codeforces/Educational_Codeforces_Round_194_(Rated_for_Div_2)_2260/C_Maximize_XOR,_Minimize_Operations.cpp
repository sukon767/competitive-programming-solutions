//sukon always reads the entire problem statement.
void solve() {
    ll x, y; cin >> x >> y;
    ll z = x+y;
    ll ans = 0;
    for(int i = 30; i >= 0; i--) {
        if((z>>i&1) && ((ans | (1LL<<i)) <= x)) {
            ans |= (1LL<<i);
        }
    }
    cout << x+y << " " << x-ans;
}

//king of the sun o_O
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    int t; cin >> t;
    //int t = 1;
    while(t--) {
        solve();
        if(t)   cout << "\n";
    }
}

