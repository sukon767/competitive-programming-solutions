void solve() {
    int n; cin >> n;
    string s = "+";
    while(sz(s) + 3 <= 767) s += "--+";
    cout << s << endl;
    int k; cin >> k;
    if(k == 0) cout << n << endl;
    else {
        assert(k%3 == 1);
        int ans = (n+1 + (k-1)/3);
        assert(ans <= 2*n);
        cout << ans << endl;
    }
}

