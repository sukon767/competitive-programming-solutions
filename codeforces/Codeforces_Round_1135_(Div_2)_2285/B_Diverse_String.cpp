//sukon always reads the entire problem statement.
void solve() {
    ll n, k; cin >> n >> k;
    string s; cin >> s;
    ll cnt = 0;
    for(char c : s) cnt += (c - '0');
    cnt = max(cnt, n-cnt);
    cnt = min(n, cnt+k);
    ll ans = 1 + (cnt)*(cnt+1)/2 + (n-cnt)*(n-cnt+1)/2;
    cout << ans;
}

