int stuff(vector<vector<int>> a) {
	map<int, int> mp;
	int p = 0;
	for (auto& x : a)
		for (int i : x)
			if (mp.find(i) == mp.end()) mp[i] = p++;
	int v = 0;
	for (auto& x : a)
		for (int i : x) v = v * 9 + mp[i];
	return v;
}
ll icbrt(ll x) {
	ll lo = 1, hi = 1e6;
	while (lo < hi) {
		ll m = (lo + hi + 1) >> 1;
		if (m * m * m <= x)
			lo = m;
		else
			hi = m - 1;
	}
	return lo;
}
